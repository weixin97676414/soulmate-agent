def upgraded_builtin_prompt(
    old_prompt: str, assistant_id: str, assistant_name: str = ""
) -> str | None:



















    if not old_prompt:
        return None
    name = (
        (assistant_name or "").strip()
        or _prompt_assistant_name(old_prompt)
        or "这个搭子"
    )
    legacy = _legacy_builtin_prompt(name)
    if _prompt_body(old_prompt) != _prompt_body(legacy):
        return None
    return builtin_prompt(name, assistant_id)


