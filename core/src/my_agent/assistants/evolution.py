"""「全员进化」的共用约定：**任务名格式** + **自建搭子的初始规则正文**。

## 这是什么

客户端里每个搭子都可以有一条「全员进化」的自动化任务：每周跑一次，让那个搭子整理
**自己的**记忆与人格（写入这一周的收获、合并重复条目、同一件事说法冲突时保留时间更新的那条）。

四个内置搭子由系统预置（见设计稿 `全员进化/客户端适配方案.md`）；**自建搭子不预置**，
改为在它的 `RULES.md` 里写一段初始规则，让它**主动问用户**要不要建一条。

## 为什么要单独成模块

这段正文与这个命名格式有**三个使用方**，而且必须逐字一致，散在三处迟早会漂：

1. 用户手工新建搭子（`server/routes/assistants.py`）；
2. AI 新建搭子（`agent/orchestrator.py` 的 `create_assistant`）；
3. 将来预置那四条内置搭子的任务时，任务名也按同一格式拼。

## 任务名的格式（产品定下的，别顺手改）

``「全员进化中 」+ 搭子的名字`` —— 例如 ``全员进化中 Soulmate``、``全员进化中 Love Buddy``。

⚠️ 「全员进化中」后面那个**空格是用户原文里的**，不要去掉、也不要换成 `·` `-` 之类的分隔符。
"""

from __future__ import annotations

#: 任务名前缀（含用户指定的那个空格）
TASK_NAME_PREFIX = "全员进化中 "

#: 初始规则那一节的标题。既用来阅读，也用来判"这段还在不在"（幂等判据）
SECTION_TITLE = "## 全员进化（系统初始规则，请勿删改本节）"

#: 给"改动**别人**的搭子"的那几个技能用的一句约束（写在技能描述里）。
#:
#: 做成共享常量而不是在三处各写一遍：模型是按**字面**理解描述的，句子一旦漂了，
#: 有的技能会拦、有的不会，而症状只是"某条规则偶尔被改坏"，几乎查不出来。
APPEND_ONLY_CLAUSE = (
    "⚠️ 只允许**追加**，不允许删改目标搭子已有的内容；尤其**不要动** RULES.md 里那段以"
    "「## 全员进化（系统初始规则」开头的规则 —— 那是系统写入的原始内容，"
    "你自己的内容只能写在文件的其他部分。"
)


def task_name(assistant_name: str) -> str:
    """按统一格式拼出一个搭子的进化任务名。

    名字为空时退回 ``全员进化中`` 本身（不带尾巴）—— 宁可名字难看，也不要拼出一个
    以空格结尾的任务名，那种名字在列表里看着像坏的。
    """
    cleaned = (assistant_name or "").strip()
    return f"{TASK_NAME_PREFIX}{cleaned}" if cleaned else TASK_NAME_PREFIX.strip()


def evolution_rule(assistant_name: str) -> str:
    """写进自建搭子 ``RULES.md`` 的初始规则正文。

    ## 写这几句的取舍

    - **只讲"怎么问、怎么建"**，不讲"进化要做什么"的细节：真正干活的指令写在**任务自己**的
      `prompt` 里（那样将来改指令不用动所有搭子的文件）。这里只规定**任务名格式**与
      **提醒礼仪**，以及 prompt 至少该覆盖哪三件事。
    - **"不同意就不再追问"要写死**：不写的话模型很可能每次都问，用户会觉得被骚扰。
    - **末尾那句"不要删改本节"是说给两种读者听的**：搭子自己（它读自己的 RULES 时会看到），
      以及被派来改这个搭子的 AI（`team_update_assistant` / `team_restructure` 只许追加）。
    """
    name = assistant_name.strip() or "这个搭子"
    wanted = task_name(name)
    return f"""{SECTION_TITLE}

每个搭子都可以有一条「全员进化」自动化任务：**每周跑一次，让那个搭子整理自己的记忆与人格**。
内置搭子由系统预置；**你自己没有**，所以要你来主动问用户。

**怎么提醒用户**：如果你名下还没有「{wanted}」这条任务，在合适的时机**主动问一次**，
一次说清三件事 —— ① 每周跑一次；② 用来整理你自己的记忆与人格；③ 会消耗一点 Token。
用户同意就建；**不同意就不再追问**（别反复问，也别不打招呼就自己建）。

**怎么建**：用 `scheduled_task_create` 建，参数照这样填：

- `name`：`{wanted}`（**必须**是这个格式：「全员进化中」后面跟一个空格，再接你的名字）
- `prompt`：写清这一轮要做什么 —— 读你自己的 `MEMORY.md`；把这一周学到的记下来（追加）；
  把重复的合并成一条；同一件事前后说法冲突时**保留时间更新的那条**
- `trigger`：`interval`（每隔一段时间）
- `interval_minutes`：`10080`（正好一周）
- `start_at`：问用户一个方便的时刻（例如"这周日凌晨三点"），格式如 `2026-10-04T03:00`
- `enabled`：`true`

**本节是系统写入的原始规则，不要删改它**；你自己的规则请写在文件的其他部分。
"""


def builtin_prompt(assistant_name: str) -> str:
    """**预置任务**的执行指令全文（四个内置搭子共用，只差开头的自称）。

    ## 为什么整篇写死在这里，而不是让搭子每次自己发挥

    这条任务一周才跑一次、无人看着，跑歪了没人当场发现。指令要把三件事定死：

    1. **边界**（只能改自己什么、哪些碰了也没用）—— 不写清楚，模型会去试被锁的
       `RULES.md` / 名称 / 简介，试失败后要么反复重试到超时，要么在报告里报一堆"系统故障"；
    2. **记忆维护的做法**（写 / 改 / 去重 / 消解冲突）—— 尤其 **不能替换成空** 这一条，
       不写的话它会一直尝试"删掉重复的那条"然后一直失败；
    3. **冲突按时间保留最新的**，判断不了就两条都留（宁可留着，也别自作主张删）。

    与 `evolution_rule()`（自建搭子的初始规则）的分工：那份只讲"怎么问、怎么建"，
    真正干活的指令在这里 —— 将来改指令不用去动所有搭子的 RULES.md。
    """
    name = assistant_name.strip() or "这个搭子"
    return f"""你是「{name}」。现在是你每周一次的自我进化时间。这一轮只处理**你自己的**人格与记忆。

【一、先说清边界，越界会被系统拒绝】
1. 你只能改你自己的东西：SOUL.md（人格）、IDENTITY.md（身份）、MEMORY.md（记忆）。
2. **不要碰 RULES.md** —— 它是出厂规则，被系统锁住，而且每次启动都会被回写，改了也不会生效。
3. **不要改你的名字、简介、可用能力** —— 同样被系统锁住。
4. **不要碰 USER.md** —— 那是"关于用户"的档案，由别的流程维护，你改了会和它打架。
5. 只用你自己的人格/记忆类技能去改，**不要用通用文件工具去动配置文件或别人的文件**。

【二、先看，再想，最后才动手】
1. 先把你自己的文件完整读一遍（重点读 MEMORY.md）。
2. 再用「长期记忆概况」和「检索长期记忆」，看看长期记忆里存了多少、哪些和你自己有关。
3. 需要时用「检索历史记录」翻一下最近和用户的对话。
4. 动手之前先用一两句话说明"我看到了什么、准备改哪几条、为什么"。
   **没有把握的就别改** —— 把不确定的地方写进最后的报告里，比乱改一遍有价值。

【三、记忆维护（这一轮的主活）】
1. **写入**：把这一周学到的东西（用户的偏好、对你的纠正、习惯、约定）追加到 MEMORY.md。
   追加会自动带上今天的日期，你不用自己写日期。
2. **修改**：记错的条目，用"把原文一字不差地替换成新内容"的方式改。
   注意：一次只能替换一处，要改多处就多调用几次。
3. **删除重复**：同一件事被记了好几遍时，只留信息最全的那一条。
   ⚠️ 你不能把内容替换成"空" —— 正确做法是把"重复的那几条连同中间的连接文字"整段作为原文，
   一次性替换成"要保留的那一条"。删之前先确认它们**确实是同一件事**，不是"看起来像"。
4. **冲突消解**：同一件事前后说法不一致时，**以时间更新的那条为准**：
   MEMORY.md 看每条上面的日期标题（形如 ### 2026-09-29）；
   长期记忆看检索结果里带的时间。
   把旧的那条改写成"已被 X 月 X 日更正"，或者干脆合并进新的那条。
   如果两条时间一样、或者你判断不出谁更新 —— **两条都留着**，并在报告里写"这里有冲突，我没敢动"。

【四、人格微调（只在有把握时做，宁可不做）】
1. 只有当你反复观察到同一种东西（例如用户三次纠正你用词太书面），才考虑微调 IDENTITY.md 或 SOUL.md。
2. 微调是**补充和修正**，不是重写：不要删掉出厂设定的核心，不要改动"你是谁"。
3. 一次最多改一到两处，改完把内容读回来确认一遍。

【五、做完之后】
1. 每改完一步就把文件读回来确认结果，不要连改好几处再一起检查。
2. 中途失败或被打断也没关系：**已经改好的部分保留**，不要试图"恢复原样"。
3. 最后用三段话收尾：
   ① 本次改动：改了什么、每一处为什么；
   ② 没动的：哪些看着该整理但我没动、为什么（证据不足 / 拿不准）；
   ③ 给用户的：这一周我观察到的一两件事（例如"你最近三次都在晚上问同一个问题"）。
4. 只报告你**真的做过**的事和**真的看过**的文件；没看的就写"没看"。
"""


def with_evolution_rule(rules: str, assistant_name: str) -> str:
    """把初始规则补进一段 RULES 正文里；已经有了就**原样返回**。

    幂等靠"标题还在就跳过"判断，不用另做标记文件 —— 理由：这段正文是给人（和模型）看的，
    用户把它删了就是明确的不要，系统不该偷偷补回去（那会和"用户手改算数"的既有口径打架）。
    """
    if SECTION_TITLE in rules:
        return rules
    block = evolution_rule(assistant_name)
    body = rules.rstrip()
    return f"{body}\n\n{block}\n" if body else f"{block}\n"
