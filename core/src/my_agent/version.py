"""版本号的**唯一来源**。

为什么不直接写在 ``my_agent/__init__.py`` 里：那样 ``server/app.py`` 与
``server/routes/system.py`` 要拿到它就得 ``from .. import __version__``，
而这条导入依赖"包的 ``__init__`` 已经执行完"这个时序假设 —— 一旦将来
``__init__`` 里引入了会反向导入 ``server`` 的东西，就会变成循环导入。

单独放一个**没有任何导入**的小模块，谁都能安全地引用它。

之前这两处各自硬编码了一个 "0.1.0"：每次发版都得靠人记得改，而它们
恰恰是最容易被忘掉的地方（改了 ``__init__`` 却没改这两处，界面上显示的
版本就会和实际发布的不一致）。
"""

# ⚠️ 开发期**固定**这个值，发版时才按流程升（第 91 批，L-17 澄清了这里的口径）。
# 上面 docstring 里提到的 "0.1.0" 是**历史**：那是当年两处各自硬编码的值，
# 说明的是"为什么要把版本号收拢到这一个文件"，**不是**当前版本。
# 反过来说：谁看到 docstring 就照着去改这个数，都是改错了地方。
#
# 顺带记住另外三处版本号的关系（都不该"顺手对齐"）：
#   · `desktop/package.json` 同样是 0.0.1（与这里一致）；
#   · `IconRail` 的兜底文案也是 `0.0.1`（拿不到 appInfo 时显示）；
#   · `core/dist/` 与 `release/` 里那些 **0.1.x** 是**已打包的旧产物**，
#     它们只代表"那个包是什么时候打的"，重建核心/重新打包才会变。
__version__ = "0.0.1"
